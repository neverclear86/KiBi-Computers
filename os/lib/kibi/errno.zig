/// [code]（成功なら 0）を、成功なら何もせず、失敗なら [Error] にする
pub fn check(code: u16) Error!void {
    if (code == 0) return;
    return toError(@enumFromInt(code));
}

/// [Errno] を [Error] にする。`SUCCESS` と定義外の番号は `UNKNOWN`
pub fn toError(e: Errno) Error {
    return switch (e) {
        .SUCCESS => error.UNKNOWN,
        inline else => |tag| @field(Error, @tagName(tag)),
        _ => error.UNKNOWN,
    };
}

/// [Error] を [Errno] に戻す（`UNKNOWN` は `IO`）
pub fn fromError(err: Error) Errno {
    inline for (@typeInfo(Errno).@"enum".fields) |f| {
        if (comptime f.value != 0) {
            if (err == @field(Error, f.name)) return @enumFromInt(f.value);
        }
    }
    return .IO;
}

/// エラーの短い名前（`NOENT` など。メッセージに使う）
pub fn name(err: Error) []const u8 {
    return @errorName(err);
}

/// エラーの英語の説明（strerror 相当。主なものだけ。ほかは名前を返す）
pub fn describe(err: Error) []const u8 {
    return switch (err) {
        error.TOOBIG => "Argument list too long",
        error.ACCES => "Permission denied",
        error.AGAIN => "Resource temporarily unavailable",
        error.BADF => "Bad file descriptor",
        error.BUSY => "Device or resource busy",
        error.CHILD => "No child processes",
        error.EXIST => "File exists",
        error.FBIG => "File too large",
        error.INTR => "Interrupted",
        error.INVAL => "Invalid argument",
        error.IO => "I/O error",
        error.ISDIR => "Is a directory",
        error.LOOP => "Too many levels of symbolic links",
        error.MFILE => "Too many open files",
        error.NAMETOOLONG => "File name too long",
        error.NOENT => "No such file or directory",
        error.NOEXEC => "Exec format error",
        error.NOMEM => "Out of memory",
        error.NOSPC => "No space left on device",
        error.NOSYS => "Function not implemented",
        error.NOTDIR => "Not a directory",
        error.NOTEMPTY => "Directory not empty",
        error.NOTSUP => "Not supported",
        error.NOTTY => "Not a tty",
        error.PERM => "Operation not permitted",
        error.PIPE => "Broken pipe",
        error.RANGE => "Result out of range",
        error.ROFS => "Read-only file system",
        error.SRCH => "No such process",
        error.XDEV => "Cross-device link",
        error.NOTCAPABLE => "Capabilities insufficient",
        else => @errorName(err),
    };
}
