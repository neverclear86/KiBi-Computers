package pro.ikili.kibicomputers.core.kernel.process

/**
 * ゲストからカーネルに入る口で、スタックの余裕を先に確かめる（#828）。
 *
 * ゲストの深い再帰（コンポーネントの相互再帰など）では、スタックはどの深さでも尽きうる。尽きる位置が、カーネルのロック
 * （マシンのロック・CPU・許可）を取る・放す途中や、`holdsCpu`・`holdsPermit` の印と実際の持ち物を合わせる途中だと、
 * ロックが残る・CPU や許可が返らない・待ち手が起こされない、のどれかになり、そのマシン（許可ならサーバー全体）が止まる。
 * `finally` で取り戻そうとしても、同じ深さなのでまた溢れる。
 *
 * そこで、ゲストからカーネルに入る 2 つの口（`ProcessContext.hostFunction` の包みと、燃料切れの処理）の先頭で、決まった量の
 * スタックを使う再帰（[probe]）を 1 回だけ動かす。CPU・許可を返して取り直す深い道に入る直前（燃料切れの処理の `onFuelExhausted` と、
 * ホストの関数の本体から止まって待つ口の `block`・`awaitHost`）でも、もう 1 回大きく確かめる（[FUEL_YIELD_FRAMES]）。そこで `StackOverflowError` が出たら、ロックも CPU も許可も触らずに、
 * その `StackOverflowError` を投げ直す（ゲストの再帰で尽きたのと同じく、プロセスだけが `call stack exhausted` で終わる）。
 * 通れば、次にゲストを呼ぶまでのホストの区間（ADR 0043 の 48 行目により、カーネルロックの中でゲストを呼ばないので、深さに上限がある）は、
 * 確かめた分の余裕の中で動く。
 *
 * JVM は、メソッドに入るたびに、その先のシャドーゾーン（ネイティブのコードと JVM の中の処理のための数十 KiB）が残っているかを確かめる。
 * [probe] が通れば、ロックを取る時点で「シャドーゾーン + 確かめた分」が残っている。確かめた分は、ホストの区間でカーネルのロックを
 * 持つところまでのフレーム（Java のコードの分）に当てる。
 *
 * 1 段で使うバイト数は、フレームの大きさ（インタプリタか JIT か）で変わる。段数は、256 KiB のスタックで尽きる位置を 1 段ずつずらして
 * 確かめた結果（`StackExhaustionLockTest`。確かめがないと JDK のロックの中で尽き、燃料切れの処理では CPU が返らなくなった）に
 * 余裕を持たせて決めた。JIT の後で、32 段は約 6 KiB、128 段は約 23 KiB を使い、1 回あたり約 0.2 µs・約 0.9 µs かかる
 * （#828 の PR の設計メモ）。値はバランスの値でないので、コンフィグにしない。
 *
 * 呼ばれ方と費用:
 * - ホストの関数の包みと燃料切れの処理の入口は、呼ばれるたびに 32 段（約 0.2 µs。ロック 1 回程度）を払う。前借り（#477）の間は、
 *   残りが負の間じゅう燃料切れの処理が関数の入口・loop の先頭ごとに呼ばれる（`FUEL_OVERDRAFT_LIMIT` まで）。そのほとんどは、確かめの手前の
 *   速い道（#887。欄を読むだけの条件の関数 `ProcessRuntime.canSkipOverdraftCheck` を 1 段呼ぶほかは、ロックにも共有の状態にも触らず、
 *   何も書き換えずに負の残りを返す）で抜けるので、確かめを払わない。
 *   確かめを払うのは、前借りの始まりと `FUEL_OVERDRAFT_RECHECK` ごとの遅い道（カーネルロックを取る）だけ
 * - 128 段（約 0.9 µs）は、次の 2 か所で払う。
 *   - 燃料切れの処理が CPU・許可を返して取り直す道（`onFuelExhausted`）に入る直前。通るたびに新しいスライスを受け取る
 *     （スライスごと。前借りの間は通らない）
 *   - ブロッキング型の止まって待つ口（`block`・`awaitHost`。`awaitHost` を使う `callOnMainThread` などを含む）の先頭。呼ぶたびに払い、
 *     `block` はすぐそろっていて待たないときも払う（待つかどうかは、カーネルロックの中で待ちを登録してからでないと分からず、
 *     登録した後に尽きると待ちが残るため、先頭で確かめる）。どちらも、呼ぶたびに CPU・許可を返して取り直すか、
 *     少なくともカーネルロックで待ちを登録する口なので、0.9 µs はその費用に比べて小さい
 *
 * 段数の根拠（ホストの関数の本体を含む）: ホストの関数の本体の奥でロックを取る道（`awaitHost`・`block` → `releasePermitAndCpu` →
 * `acquireCpu` → CPU・許可の取り直しと条件変数の待ち）も、燃料切れの処理の深い道と同じ列を通る。段数を縮めて同じテストを回した結果
 * （JDK 17・Windows）、`awaitHost` を本体にしたテストは包みが 2 段で落ち、8 段では通った。燃料切れの処理は入口 2 段・深い道 8 段でも通った。
 * ただし、CI（Linux・JDK 17）では、`awaitHost` の先頭に確かめがなかったとき（包みの 32 段だけ）に、`awaitHost` を本体にしたテストが
 * 止まった（犠牲のプロセスが終わらず時間切れ。何が残ったかはログに出ておらず、確かめられていない。#828 の PR）。
 * フレームの大きさは OS・JIT の段階で変わるので、Windows で測った「通った最小の 4〜16 倍」は、どの環境でも足りる根拠にはならない。
 * そこで、CPU・許可を返して取り直す道の手前は、どれも 128 段で確かめる形にした（`block`・`awaitHost` の先頭にも足した）。
 * 32 段は、包みと燃料切れの処理の入口から、ロックの区間を抜けるまで（とホストの関数の本体の浅い処理）に当てる。
 * 足りなかったときに残ったものは、浅いところの安全網（`ProcessRunner.recoverLeaks`）が見つけて戻す。
 *
 * 道ごとの確かめ（#858）: 次の道も、本体を置いたテストで、尽きる位置をずらして確かめた。毎回、尽きた位置（SOE のスタックトレース。
 * テストの `SoePositions`。区画の分け方は `SoePositionsTest` が確かめる）を区画に分けて数え、(1) ロックを取る・放す途中（AQS・`Unsafe` の CAS を含む。一番上でなく、ロックの機構を飛ばした呼び手で見る）で
 * 尽きていないこと、(2) 毎回の後の状態（マシンのロック・リースのロック・表示デバイスのロック・CPU・許可・コンソールの出力の予約）が戻ること、を確かめる。
 * 本体（VFS・端末・NIO）の中で尽きた位置は、確かめを通った後に起きるふつうの位置なので数えるだけで、安全かは (2) で見る
 * - ディスクの VFS（`DiskFileSystem`。道の解決はカーネルロックの中、I/O はロックの外でリースのロックを取る）: ロックの面だけでは足りない。
 *   本体が「ホストの移動 → node の表の付け替え」「ホストのファイルを閉じる → 開いたままの枠を返す」の間で尽きると、表・使用量・枠がホストと食い違う
 *   （カーネルのロックも CPU も壊れないので、ロックの面の確かめでは見えない）。そこで 2 つで確かめた
 *   - `DiskFileSystemStackExhaustionTest`: 本物のディスクの操作（`stat`・作る・書く・開いたままにする・閉じる・消す・名前を変える・置き換える・
 *     ディレクトリごと名前を変える）を、スタックの小さいスレッドで、尽きる境目から先の幅（操作が使う分）を詰め物 1 段ずつ動かし、毎回の後に
 *     `DiskFileSystem.consistencyProblemsForTest`（表・使用量・枠がホストと合うか）とリースのロックを確かめる。確かめを入れる前は、
 *     入口の確かめを外した（0 段にした）手元の試験では、閉じる（`release`）の途中でホストのファイルを閉じてから枠を返すまでの間に尽きて、
 *     枠が返らず、開いたままの枠 1 に対して開いているファイルが 0 になった（`RELEASE`）。そのほかの操作（`rename` の「ホストの移動 → 表の付け替え」、
 *     作る「ホストのファイルを作る → 使用量を数える」を含む）は、尽きた位置がホストの I/O・VFS の中に落ちても食い違いは見つからなかったが、
 *     窓がないとは言えない（幅は詰め物 1 段ずつで通っただけ）。そこで、ディスクの操作の入口（`io`・`release`）で [HOST_IO_FRAMES] 段を、
 *     何も変える前に確かめる形にした。入れた後は、どの操作も、尽きた位置はほぼすべて確かめの中（`StackHeadroom`）で、食い違いは 1 回も出ない。
 *     fd の表から閉じる道（`Vfs.releaseLater` → `Vfs.drainDeferred` → `release`）は、`drainDeferred` が知らせを列から取り出した後に
 *     `release` の確かめで投げると知らせが捨てられるので、取り出す前に [DEFERRED_RELEASE_FRAMES] 段を投げずに確かめ（[hasHeadroom]）、
 *     足りなければ取り出さずに返す（`drainDeferred` は、ファイルシステムに届く操作からゲストのスレッドの深さでも走る）。
 *     同じテストの、fd の表から閉じる知らせの回が、知らせが行われたか列に残ったかのどちらかになることを見る。
 *     fd の表に入れない開いたファイルを閉じる道（`Vfs.close` → `release`）は、`retained` を `release` が戻ってから落とす
 *     （途中で尽きても閉じ直せる。#901）。本番の呼び手は閉じ直さないので、開く側（`Vfs.open`）が何も変える前に [VFS_OPEN_FRAMES] 段を払い、
 *     同じ深さの `close` の確かめが通るようにする。同じテストの `Vfs` の回は、閉じる途中で尽きても閉じ直せば、また開いて書いて
 *     `finally` で閉じる本番の形では閉じ直さなくても、開いたままのホストのファイルが残らないことを見る（閉じる途中で尽きる回は、
 *     並べ替える前は閉じ直せずに落ちた。本番の形の回は、開く側の確かめがなくても手元では落ちなかった。`open` の中の確かめは `close` より数段深いため）。開く側の確かめそのものは、`refuseOpen` の 3 つの試験（作る・既存を開く・`O_TRUNC`）が、`VFS_OPEN_FRAMES` の確かめが通らない最初の深さで開き、何も変えずに断ること（作ったファイル・切り詰め・開いたままの枠・予約した枠が残らず、浅いところで開き直せる）を固定する。確かめを外す・`reserveOpen` の後ろへ動かすと落ちる。
 *     「深いスレッドが積んだ知らせを、起動用のスレッドが行う」道（`Machine.scheduleVfsDrain`）は、`P1DiskCloseStackExhaustionTest` が、
 *     本物の WASI p1 の `path_open`・`fd_close` をスタックの底に近いところで繰り返して、Machine ごと通す（毎回の後に、知らせが残らず、
 *     開いたままの枠が 0 に戻り、ディスクの状態がホストと合うこと）。
 *     入口の確かめの `StackOverflowError` は、呼び手が飲まずに伝える（`Vfs.readDirectory` がマウントの根の `stat` の失敗を node 0 に
 *     するのは `Exception` だけで、`Error` は伝える）。
 *     `/tmp`（`TmpFileSystem`）の変える操作は、#883 で入口に [TMPFS_FRAMES] 段の確かめを足し、木と使用量の食い違いも
 *     `TmpFileSystem.consistencyProblemsForTest` で見るようにした（下の「`/tmp`」）。木の食い違いの道全般の掃引（#902）でも、32 段のまま食い違いは出ない
 *   - `StackExhaustionLockTest` の `DISK_IO`: プロセスの中から、回ごとに 1 種類の操作（深いディレクトリの `stat`・別のディスクの `stat`・
 *     `open`（作る）・書く・閉じる・同じマウントの `rename`・マウントをまたぐ `rename`）を、スタックの底に近いところのホストの関数で動かす
 *     （1 本に 40 回。底に近いところだけ本物の操作をするので、1 本が約 9 秒）。毎回の後に、ディスクの表・使用量・枠がホストと合うことと、
 *     開いたままのホストのファイルが残っていないことも見る
 * - 端末への書き込みと、画面のデバイスのロックを取る出力の流し込み（`flushConsole` → `pumpConsole`。同じく `CONSOLE`）。1 本で 60 回
 *   （冷えた道は 15 回）。毎回の後に、コンソールの出力の予約（`consolePumpsReserved`）が 0 に戻ることも見る。予約はロックでないので
 *   安全網の対象外だが、持ち主のプロセスの終わり（`finishLocked`）が戻す（#890。尽きた位置に左右されない。窓を決まった形で突く
 *   `ConsolePumpReservationTest`）。確かめの段数を縮めて（包み・燃料切れの入口・深い道を 16・16・64 段、8・8・32 段）この回を回しても、
 *   毎回の後に予約が 0 に戻った（JDK 17・Windows。尽きた位置はほとんど確かめの中で、予約の窓に落ちた回は少ない。窓は上のテストが見る）
 * - canon の lift・lower（文字列の realloc、post-return、別のインスタンスが lower した関数を lift し直す `CoreRef.Lowered` の道。
 *   本物の Endive のコンポーネント。`ComponentStackExhaustionLockTest`）。入口の `top` に止まりうるホストの関数を置くので、待機点型の回は
 *   待機点型に固有の燃料切れの道を通る: 深い `f`（ゲストからゲストへの呼び出しの下）の中の前借りと、`top` の loop の先頭の燃料切れの巻き戻し・巻き直し
 *   （`onComponentFuelExhaustedUnwindable` → `requestUnwind`）。巻き戻しは `top` でしか起きないので、`f` を呼ばず `wait` と燃料を使う loop だけの入口 `wind`
 *   を、詰め物を尽きる境目の近くまで積んで動かす回（`edgeSweep`。境目は二分探索で 1 段の精度で探し、その後は境目の 16 段手前から
 *   320 段先までを回数で等分した刻み（96 回で約 3.3 段、冷えた道で約 13 段）でずらす）で、境目の近くの巻き戻し・巻き直しを確かめる。
 *   `edgeSweep` で確かめられるのは「境目の近くで入口の確かめを通った回は、巻き戻して巻き直し、最後まで終わる」まで（1 回目の通りと巻き直しの
 *   通りの詰め物が同じなので、巻き直した後に尽きるのは入口の確かめの中（`PROBE`）になる）。巻き直しの最中は、巻き直しの通りでだけ詰め物を
 *   足す `rewindSweep`（#903）が当てる: 燃料待ちからの再開で `LinkedComponent.call` に入ってから、止まった `kibi.async_fuel` に着くまで
 *   （lift・`wind` の巻き直し・燃料切れの処理の入口の確かめ）で尽きた回が、下の JVM・OS のどれでも出た（1 本に 40〜151 回。うち確かめの外の
 *   Endive・canon の中が 12〜33 回。この数は、窓の上側まで刻みを届かせ、窓の探し直しを足す前の版（#903 の 0626ce07・e1918e4d）で測ったもの。
 *   直した後の版は Windows の JIT（JDK 17・21）・冷えた道・`-Xint` で回し、1 本に 39〜149 回、うち確かめの外が 14〜55 回。Linux と段数を
 *   縮めた回は直す前の版の結果のまま。確かめの外で 1 度も尽きなければ `rewindSweep` が落ちる）。どの回もロックの途中でなく、プロセスだけが終わり、退避した値（`asyncStack`）は残らず、同じ台の次の
 *   プロセスは巻き戻し・巻き直しを経て期待値で終わった。巻き戻しの最中（`requestUnwind` から、ドライバーが `WaitFuel` を返すまで）で尽きた回は
 *   0 回で、構造上起きない: 巻き戻しを求めるのは燃料切れの処理の入口の確かめ（[FUEL_HANDLER_FRAMES]）を通った後で、その後の
 *   `requestUnwind`・ゲストの `kibi.async_push` は確かめより浅いところで動き、`waitFuelUnwound` はドライバーが詰め物の外へ戻った後に動くので、
 *   1 回目の通りの詰め物を増やすと先に確かめで尽きる。本番の巻き直しは `WasiP2Driver` が浅いところから始める（`beginRewind` も同じ）ので、
 *   巻き直しの通りで余裕が減るのは、巻き直しの枝のフレームが 1 回目の通りより大きいとき（JIT が巻き直しの枝を外したとき）だけで、`rewindSweep` はそれを詰め物で模して確かめる。
 *   `top`・`edge` では、1 回の実行でいちばん深いのが `f` の連鎖（echo の包みの確かめ 32 段、realloc の中の `ensure(128)`）の先になり、巻き戻しの道は
 *   その分浅いところで動くので、入口の確かめが「ぎりぎり通る」深さには届かない（前の `edgeSweep` はこちらで、巻き戻しの道を確かめ切れていなかった）。
 *   `wind` は境目を決めるのが巻き戻し・巻き直しの道そのものなので、境目の手前（終わる側）の回では、巻き戻して巻き直した後の結果が期待値と合うことも見る
 * - 本物の p1 のモジュールの燃料切れ（前借り、待ち点への変換と巻き戻し。`P1StackExhaustionLockTest`）
 * 今の段数（32・32・128、ディスクの操作は入口で 128）の測り直し（#903。ディスクの入口・`drainDeferred`・`/tmp`・`ctx.instantiate` の確かめと、
 * #922・#924・#949・#950 の後の main（62855077）に、テストだけを足して測った）: 次のどの組み合わせでも、上のすべてのテスト
 * （`DiskFileSystemStackExhaustionTest`・`P1DiskCloseStackExhaustionTest` を含む）が通り、尽きた位置を数えて、ロックの途中（`LOCK`・`JDK_LOCK`）は 0 回、
 * 毎回の後の状態も戻った。尽きた位置は、ほぼすべて確かめの中（`StackHeadroom`）で、外は、コンポーネントの境目・巻き直しの通りを回す回の
 * 詰め物の再帰・ランタイムの中と、ディスクの掃引のテストのコードの中（境目から先の幅を回すので、詰め物そのものが尽きる回）、本体の中の数回だけ
 *   - JIT（JDK 17・21）: Windows（Corretto 17.0.12・21.0.4）、Linux（WSL2 の Ubuntu 20.04。Temurin 17.0.21.1・21.0.13.1。CI のランナーそのものではない）
 *   - 冷えた道（JDK 17）: Windows・Linux（回数は 1/4。ディスクの 2 つは回数を戻して（`-Pkibi.stackHeadroom.roundsScale=1`）も回した）
 *   - `-Xint`（JDK 17）: Windows（全体で約 13 分。回数は 1/4）、Linux（約 24 分）。ディスクの掃引の幅を回数の割合で縮めていたので、`-Xint` では `sweepVfs` の幅が確かめの幅に届かず落ちた。幅は縮めない形に直した（#903）
